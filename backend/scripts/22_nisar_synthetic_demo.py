"""
Script 22: build a clearly labelled SYNTHETIC GCOV-like product so the API and frontend have something to render.

Nothing in the output is NISAR data. Pixel values are generated. The dates and times are the pass slots of the real catalogue
manifest (script 19) so charts line up with real rainfall dates; the product IDs are "SYNTHETIC-FIXTURE-<date>".
Every manifest and API response carries dataKind "synthetic" and a warning.

Run it:
    python scripts/22_nisar_synthetic_demo.py
    python scripts/22_nisar_synthetic_demo.py --manifest data/cache/nisar/nisar_manifest_t032_D_f081_m4005.json --max-dates 6

Output: data/output/camanava_2026/nisar/ (refuses to replace a REAL product unless --force).
Fixture HDF5 files go to data/raw/nisar_synthetic/ (git-ignored).
"""
import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from processing.nisar_flood import pipeline, synthetic  # noqa: E402
from processing.nisar_flood.constants import BACKEND_DIR, STUDY_BBOX  # noqa: E402

DEFAULT_MANIFEST = BACKEND_DIR / "data" / "cache" / "nisar" / "nisar_manifest_t133_D_f081_m4005.json"
FIXTURE_DIR = BACKEND_DIR / "data" / "raw" / "nisar_synthetic"


def synthetic_manifest(real: dict, max_dates: int | None) -> dict:
    rows = real["gcov"][:max_dates] if max_dates else real["gcov"]
    out_rows = []
    for row in rows:
        out_rows.append({
            "title": f"SYNTHETIC-FIXTURE-{row['date']}", "date": row["date"], "acquisitionTime": row["acquisitionTime"],
            "acquisitionTimeManila": row.get("acquisitionTimeManila"), "url": None, "sizeBytes": None, "md5": None,
            "collectionShortName": "SYNTHETIC (not a NISAR collection)", "maturity": "synthetic", "productVersion": None,
            "bboxCoverageFraction": None})
    return {"gcov": out_rows, "selection": real["selection"], "retrievedAt": real["retrievedAt"], "warnings": []}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--manifest", default=str(DEFAULT_MANIFEST), help="script-19 manifest whose date slots to reuse")
    parser.add_argument("--max-dates", type=int)
    parser.add_argument("--out-dir", default=str(pipeline.OUTPUT_DIR))
    parser.add_argument("--spacing", type=float, default=30.0, help="fixture pixel size in metres")
    parser.add_argument("--force", action="store_true", help="replace an existing REAL (observed) product")
    args = parser.parse_args(argv)

    out_dir = Path(args.out_dir)
    existing = out_dir / "manifest.json"
    if existing.is_file() and not args.force:
        try:
            kind = json.loads(existing.read_text()).get("dataKind")
        except (OSError, ValueError):
            kind = None
        if kind == "observed":
            print(f"error: {existing} holds a REAL (observed) product; pass --force to replace it with synthetic data.", file=sys.stderr)
            return 2

    real = json.loads(Path(args.manifest).read_text())
    fake = synthetic_manifest(real, args.max_dates)
    levels = synthetic.flood_levels(len(fake["gcov"]))
    FIXTURE_DIR.mkdir(parents=True, exist_ok=True)
    for index, (row, level) in enumerate(zip(fake["gcov"], levels)):
        block = (120.97, 14.66, 121.04, 14.72) if index == 3 else None  # one pass with a gap in coverage: exercises nodata handling
        synthetic.write_synthetic_gcov(FIXTURE_DIR / f"{row['title']}.h5", level=level, seed=1000 + index,
                                       nodata_block=block, spacing=args.spacing)
    passes = pipeline.passes_from_cmr_manifest(fake, local_dir=FIXTURE_DIR, cache_dir=None, reuse_cache=False)
    analysis = pipeline.analyse(passes, bbox=STUDY_BBOX, calibrate=True)
    source = {"name": "SYNTHETIC fixture generated by scripts/22_nisar_synthetic_demo.py (not NISAR data)", "url": None,
              "version": "synthetic-1", "slotDatesFrom": Path(args.manifest).name}
    track = {k: real["selection"][k] for k in ("track", "direction", "frame", "mode")}
    track["note"] = "date and time slots copied from the real catalogue; the pixels are synthetic"
    path = pipeline.export_product(analysis, out_dir, data_kind="synthetic", source=source, track=track,
                                   verification={"layout": "synthetic", "evidence": ["generated by synthetic.py"]},
                                   provenance={"generator": "processing/nisar_flood/synthetic.py", "levels": levels, "spacingM": args.spacing})
    pipeline.save_rule(out_dir / "water_rule.json", analysis.rule)
    print("Wrote SYNTHETIC product:", path)
    print(f"  {len(passes)} passes; flooded km2 per pass: {[s['floodedKm2'] for s in analysis.pass_stats]}")
    print(f"  half-or-more km2: {analysis.rhythm_stats['halfOrMoreKm2']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
